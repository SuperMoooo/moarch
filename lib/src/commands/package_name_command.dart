import 'dart:io';

import 'package:args/command_runner.dart';
import 'package:mason_logger/mason_logger.dart';
import 'package:path/path.dart' as p;

import '../utils/app_id_utils.dart';
import '../utils/project_manifest.dart';

/// `moarch package-name <id>` — replaces the `com.example.<name>` that
/// `flutter create` writes with the app's own id, on every platform, and
/// moves `MainActivity` to the folder of its new package.
class PackageNameCommand extends Command<int> {
  /// Creates the package-name command.
  PackageNameCommand({required Logger logger}) : _logger = logger {
    argParser
      ..addOption(
        'path',
        abbr: 'p',
        defaultsTo: '.',
        help: 'The project root, where pubspec.yaml is.',
      )
      ..addOption(
        'ios-bundle-id',
        valueHelp: 'id',
        help:
            'A different id for iOS and macOS. Defaults to <id> with any '
            'snake_case segment in camelCase (my_app → myApp), since Apple '
            'ids cannot contain `_`.',
      )
      ..addFlag(
        'dry-run',
        abbr: 'd',
        negatable: false,
        help: 'List what would change without writing anything.',
      );
  }

  final Logger _logger;

  @override
  String get name => 'package-name';

  @override
  List<String> get aliases => const ['bundle-id'];

  @override
  String get description =>
      'Give the app its own id (e.g. com.acme.shop) in place of '
      'com.example.*: applicationId, namespace, the bundle ids, every file '
      'that mentions them, and MainActivity moved to the new package.';

  @override
  String get invocation => 'moarch package-name <id>   (e.g. com.acme.shop)';

  @override
  Future<int> run() async {
    final rest = argResults?.rest ?? const <String>[];
    if (rest.length != 1) {
      _logger.err('Say which id to use: $invocation');
      return 64;
    }
    final androidId = rest.single.trim();
    final appleId =
        (argResults?['ios-bundle-id'] as String?)?.trim() ??
        AppIdUtils.appleIdFor(androidId);
    final root = p.normalize(p.absolute(argResults?['path'] as String? ?? '.'));
    final dryRun = argResults?['dry-run'] as bool? ?? false;

    final problem =
        AppIdUtils.androidIdProblem(androidId) ??
        AppIdUtils.appleIdProblem(appleId);
    if (problem != null) {
      _logger.err(problem);
      return 64;
    }
    if (!File(p.join(root, 'pubspec.yaml')).existsSync()) {
      _logger.err('No pubspec.yaml at $root.');
      return 1;
    }

    final plan = AppIdUtils.plan(root, androidId: androidId, appleId: appleId);
    if (plan.declared.isEmpty) {
      _logger.err(
        'No android/ or ios/ app to rename at $root — '
        'run `fvm flutter create .` first.',
      );
      return 1;
    }
    if (androidId.startsWith('com.example.')) {
      _logger.warn(
        'Google Play refuses `com.example` ids — this is a '
        'placeholder too.',
      );
    }
    if (plan.isEmpty) {
      _logger.info('  Already $androidId — nothing to change.');
      return 0;
    }

    _report('Android', plan.android);
    _report('iOS/macOS', plan.apple);
    if (plan.conflicts.isNotEmpty) {
      _logger.err(
        'MainActivity cannot move: these already exist in the new '
        "package's folder:",
      );
      for (final path in plan.conflicts) {
        _logger.err('    $path');
      }
      return 1;
    }

    final moved = {for (final move in plan.moves) move.from: move.to};
    final edited = plan.edits.keys.where((path) => !moved.containsKey(path));
    _logger.info('');
    for (final path in edited) {
      _logger.info('  ${_relative(root, path)}');
    }
    for (final move in plan.moves) {
      _logger.info(
        '  ${_relative(root, move.from)}\n'
        '    → ${_relative(root, move.to)}',
      );
    }
    for (final path in plan.firebaseConfigs) {
      _logger.warn(
        '$path still names the old id. It is generated by Firebase for the '
        'app registered there, so it is left alone: add $androidId to the '
        'Firebase project and run `flutterfire configure`.',
      );
    }

    if (dryRun) {
      _logger.info('\n  Dry run — nothing written.');
      return 0;
    }

    await AppIdUtils.apply(root, plan);
    final count = edited.length + plan.moves.length;
    _logger
      ..success(
        '\n  The app is $androidId'
        '${appleId == androidId ? '' : ' ($appleId on iOS/macOS)'} — '
        '$count file${count == 1 ? '' : 's'} updated.',
      )
      ..info(
        '  Run `fvm flutter clean` before the next build: Gradle and Xcode '
        'keep the old id in their caches.',
      );
    return 0;
  }

  /// One line per platform: the old ids and the one replacing them.
  void _report(String platform, Map<String, String> renames) {
    if (renames.isEmpty) return;
    final olds = renames.keys.toList()..sort();
    _logger.info(
      '  ${platform.padRight(10)}${olds.join(', ')} → ${renames.values.first}',
    );
  }

  String _relative(String root, String path) =>
      ProjectManifest.relativeKey(root, path);
}
