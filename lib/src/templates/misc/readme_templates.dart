## 5. How the architecture works

Follow one piece of data from the server to the screen. This is a `profile`
feature; every feature in `lib/features/` has the same shape.

### `domain/` — the rules

An **entity** is a plain Dart object. No JSON, no packages, no Flutter:

```dart
// lib/features/profile/domain/entities/profile_entity.dart
class ProfileEntity {
  const ProfileEntity({required this.id, required this.name});

  final String id;
  final String name;
}
```

A **repository interface** is what the feature promises it can do — never how:

```dart
// lib/features/profile/domain/repositories/profile_repository.dart
abstract interface class ProfileRepository {
  Future<List<ProfileEntity>> fetchAll();
}
```

Nothing under `domain/` imports ${withDio ? 'Dio, ' : ''}Firebase or Flutter. That is the
point: these files can be tested with a plain `dart test`, and they survive
every change to the API, the client and the UI.

### `data/` — the world

A **model** is the entity plus serialisation:

```dart
// lib/features/profile/data/models/profile_model.dart
class ProfileModel extends ProfileEntity {
  const ProfileModel({required super.id, required super.name});

  factory ProfileModel.fromJson(Map<String, dynamic> json) => ProfileModel(
        id: json['id'] as String,
        name: json['name'] as String,
      );

  Map<String, dynamic> toJson() => {'id': id, 'name': name};
}
```

It **extends** the entity, so it can be returned anywhere an entity is
expected. The UI is handed `ProfileEntity` and never learns that JSON exists.

A **datasource** is where the bytes come from${withDio ? ' — an HTTP call through the shared\nDio client' : ''}. A **repository implementation** puts
the two together and is the only class that satisfies the interface:

```dart
// lib/features/profile/data/repositories/profile_repository_impl.dart
class ProfileRepositoryImpl implements ProfileRepository {
  ProfileRepositoryImpl(this._remote);

  final ProfileRemoteDataSource _remote;

  @override
  Future<List<ProfileEntity>> fetchAll() => _remote.fetchAll();
}
```

### The wiring: `lib/config/di/injector.dart`

One file knows both sides — which implementation answers which interface. It
uses **get_it**, a service locator:

```dart
getIt.registerLazySingleton<ProfileRepository>(
  () => ProfileRepositoryImpl(getIt<ProfileRemoteDataSource>()),
);
```

Anywhere else in the app, `getIt<ProfileRepository>()` hands back that instance
— and the caller only ever sees the interface type.

- `registerLazySingleton` — built on first use, one instance for the app's life.
  The default for repositories and services.
- `registerFactory` — a new instance every call.

> ⚠️ `injector.dart` contains a `// moarch:registrations` comment.
> `moarch create feature` inserts new registrations directly above it. Keep the
> line where it is or the tooling has nothing to anchor to.

### Errors: exactly one type reaches the UI

Everything that can fail is funnelled into `AppException`
(`lib/core/errors/app_exception.dart`)${withDio ? ', by the `safeApiCall` wrapper in\n`lib/core/network/`' : ''}. A widget never sees a
`DioException`, a `FirebaseException` or a `SocketException` — it sees an
`AppException` with a `message` written for a person.

```dart
// ✅ the data layer translates, the UI displays
try {
  final profiles = await repository.fetchAll();
  // …
} on AppException catch (e) {
  // e.message is safe to show
}

// ❌ never
try {
  // …
} catch (_) {}                       // a swallowed error is a bug you cannot find
catch (e) { showDialog(text: '\$e'); }  // stack traces are not user-facing
```

Two rules follow from that, and section 11 repeats them because they are the
ones most often broken:

1. **Never leave a `catch` empty.** Log it or handle it.
2. **Never show a raw error.** Show `AppException.message`.

---
''';

