## 6. State management — Riverpod

Screens do not hold their own state. Each feature has a **notifier** that owns
one immutable **state** object, and the screen watches it.

### The state

An immutable class in `presentation/states/profile_state.dart`:

```dart
class ProfileState implements ActionState<ProfileState> {
  const ProfileState({this.items = const [], this.success, this.error});

  final List<ProfileEntity> items;
  final String? success;
  final String? error;

  @override
  ProfileState copyWith({List<ProfileEntity>? items, String? success}) =>
      ProfileState(items: items ?? this.items, success: success);
}
```

Immutable means you never change it in place — you build the next one with
`copyWith`. Riverpod compares the old state with the new one to decide what
rebuilds; mutating in place leaves it nothing to compare.

### The notifier

`presentation/notifiers/profile_notifier.dart`:

```dart
final profileNotifierProvider =
    AsyncNotifierProvider<ProfileNotifier, ProfileState>(ProfileNotifier.new);

class ProfileNotifier extends AsyncNotifier<ProfileState>
    with ActionNotifierMixin<ProfileState> {
  ProfileRepository get _repo => getIt<ProfileRepository>();

  @override
  FutureOr<ProfileState> build() async {
    final items = await _repo.fetchAll();
    return ProfileState(items: items);
  }

  Future<void> rename(String id, String name) {
    return runAction((current) async {
      await _repo.rename(id, name);
      return current.copyWith(success: 'Saved');
    });
  }
}
```

Three things worth noticing:

- **`build()` is the initial load, and it is the loading state.** While its
  future runs the provider is `AsyncLoading`; if it throws, `AsyncError`. There
  is no `isLoading` boolean to set or forget.
- **`runAction` is every action after that.** It comes from
  `ActionNotifierMixin` (`lib/core/utils/action_notifier.dart`) and handles the
  loading flag, `AppException` and unknown errors for you. It hands you the
  state as it was before the action; return the state that should follow.
- **The repository comes out of `getIt`, not out of another provider.**
  `injector.dart` owns the data layer; the notifier is the seam between it and
  Riverpod.

### Reading it in a widget

```dart
class ProfileView extends ConsumerWidget {
  const ProfileView({super.key});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final state = ref.watch(profileNotifierProvider);

    return state.when(
      loading: () => const Center(child: CircularProgressIndicator()),
      error: (error, _) => Text('Something went wrong'),
      data: (profile) => ListView(
        children: [for (final item in profile.items) Text(item.name)],
      ),
    );
  }
}
```

| You want to | Use |
|---|---|
| rebuild when the state changes | `ref.watch(provider)` |
| call a method from a callback | `ref.read(provider.notifier).rename(...)` |
| react without rebuilding (snackbar, navigation) | `ref.listen(provider, ...)` |
| force a reload | `ref.invalidate(provider)` |

> ⚠️ `ref.watch` belongs in `build`, `ref.read` in callbacks — never the other
> way round. Watching inside a callback reads a value that will not update;
> reading inside `build` gives you a screen that never rebuilds.

`ProviderScope` wraps the whole app in `main.dart`. That is what makes every
provider reachable — if a provider throws "no ProviderScope found", something
was mounted above it.

