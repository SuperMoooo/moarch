  /// Every catalog slug.
  static List<String> get names => all.map((w) => w.name).toList();

  /// The widgets generated by `moarch init`.
  static List<WidgetSpec> get common => all.where((w) => w.common).toList();

  /// Looks up a spec by its CLI slug, or null if unknown.
  static WidgetSpec? byName(String name) {
    for (final spec in all) {
      if (spec.name == name) return spec;
    }
    return null;
  }

  /// Resolves [requested] to themselves plus all transitive [WidgetSpec.deps],
  /// de-duplicated. Unknown names are ignored (validate before calling).
  static List<WidgetSpec> resolve(Iterable<String> requested) {
    final resolved = <String, WidgetSpec>{};
    void visit(String name) {
      if (resolved.containsKey(name)) return;
      final spec = byName(name);
      if (spec == null) return;
      resolved[name] = spec;
      for (final dep in spec.deps) {
        visit(dep);
      }
    }

    for (final name in requested) {
      visit(name);
    }
    return resolved.values.toList();
  }

  /// The `docs/UI_KIT.md` catalog content.
  static String markdown() {
    final buffer = StringBuffer()
      ..writeln('# UI Kit — shared widgets')
      ..writeln()
      ..writeln(
          'Generated by **moarch**. These widgets live under `lib/shared/widgets/`')
      ..writeln(
          'and share one vocabulary: `variant` (primary/secondary/tertiary/danger),')
      ..writeln('`type`, `shape` and `size`.')
      ..writeln()
      ..writeln(
          'Rows marked ✅ are generated by `moarch init`. Add any other with:')
      ..writeln()
      ..writeln('```bash')
      ..writeln(
          'moarch create widget <name>     # e.g. moarch create widget switch')
      ..writeln(
          'moarch create widget all        # the whole kit + the preview screen')
      ..writeln(
          'moarch create widget --list     # print this catalog in the terminal')
      ..writeln('```')
      ..writeln()
      ..writeln(
          'Widget dependencies are pulled in automatically, and any pub packages a')
      ..writeln(
          'widget needs are added to `pubspec.yaml` (run `flutter pub get` after).')
      ..writeln();

    for (final category in categories) {
      final items = all.where((w) => w.category == category).toList();
      if (items.isEmpty) continue;
      buffer
        ..writeln('## $category')
        ..writeln()
        ..writeln('| Widget | `create widget` | Init | Notes |')
        ..writeln('| --- | --- | :---: | --- |');
      for (final w in items) {
        final notes = <String>[w.description];
        if (w.packages.isNotEmpty) {
          final pkgs =
              w.packages.map((p) => p.replaceAll(':', '').trim()).join(', ');
          notes.add('_pkg: ${pkgs}_');
        }
        if (w.needsRouter) notes.add('_needs GoRouter_');
        buffer.writeln(
          '| `${w.title}` | `${w.name}` | ${w.common ? '✅' : ''} | ${notes.join(' ')} |',
        );
      }
      buffer.writeln();
    }
    return buffer.toString();
  }
