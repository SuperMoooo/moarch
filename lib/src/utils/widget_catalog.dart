/// One entry in the shared-widget kit: everything needed to generate a widget
/// on demand and to document it in `docs/UI_KIT.md`.
class WidgetSpec {
  /// Creates a widget catalog entry.
  WidgetSpec({
    required this.name,
    required this.title,
    required this.file,
    required this.template,
    required this.category,
    required this.description,
    this.deps = const [],
    this.packages = const [],
    this.common = false,
    this.needsRouter = false,
  });

  /// CLI slug, e.g. `switch` → `moarch create widget switch`.
  final String name;

  /// Human-facing class name, e.g. `AppSwitch`.
  final String title;

  /// Path relative to `lib/shared/widgets`, e.g. `inputs/app_switch.dart`.
  final String file;

  /// Produces the widget's source.
  final String Function() template;

  /// Grouping used by the generated catalog doc.
  final String category;

  /// One-line summary for the catalog doc.
  final String description;

  /// Other widget [name]s this one imports (pulled in automatically).
  final List<String> deps;

  /// pubspec dependency lines this widget needs, e.g. `mo_2fa_code: `.
  final List<String> packages;

  /// Generated by `moarch init` out of the box.
  final bool common;

  /// Imports `config/router/app_router.dart` — needs the GoRouter option.
  final bool needsRouter;
}

